// Table config driving the generic CRUD API. `fields` are the writable columns.
export const resources = {
  stations: { table: 'PoliceStation', pk: 'station_id', fields: ['name', 'address', 'city', 'phone'],
    search: ['name', 'city'] },
  officers: { table: 'Officer', pk: 'officer_id', fields: ['badge_number', 'name', 'rank', 'phone', 'station_id'],
    search: ['name', 'badge_number'],
    select: 'SELECT o.*, ps.name AS station FROM Officer o JOIN PoliceStation ps ON ps.station_id=o.station_id' },
  criminals: { table: 'Criminal', pk: 'criminal_id', fields: ['name', 'dob', 'gender', 'address', 'status', 'photo'],
    search: ['name', 'address'] },
  cases: { table: 'Cases', pk: 'case_id', fields: ['fir_number', 'title', 'type', 'description', 'filed_date', 'status', 'officer_id'],
    search: ['title', 'fir_number', 'type'],
    select: 'SELECT c.*, o.name AS officer FROM Cases c JOIN Officer o ON o.officer_id=c.officer_id' },
  complaints: { table: 'Complaint', pk: 'complaint_id', fields: ['complainant', 'contact', 'description', 'filed_on', 'station_id', 'case_id'],
    search: ['complainant', 'description'],
    select: 'SELECT cp.*, ps.name AS station FROM Complaint cp JOIN PoliceStation ps ON ps.station_id=cp.station_id' },
  arrests: { table: 'Arrest', pk: 'arrest_id', fields: ['date', 'location', 'charges', 'case_id', 'officer_id', 'criminal_id'],
    search: ['location', 'charges'],
    select: 'SELECT a.*, cr.name AS criminal, o.name AS officer FROM Arrest a JOIN Criminal cr ON cr.criminal_id=a.criminal_id JOIN Officer o ON o.officer_id=a.officer_id' },
  evidence: { table: 'Evidence', pk: 'evidence_id', fields: ['type', 'description', 'collected_on', 'arrest_id'],
    search: ['type', 'description'] },
  courts: { table: 'Court', pk: 'court_id', fields: ['name', 'location'], search: ['name', 'location'] },
  proceedings: { table: 'CourtProceeding', pk: 'proceeding_id', fields: ['date', 'outcome', 'case_id', 'court_id'],
    search: ['outcome'],
    select: 'SELECT p.*, c.name AS court, cs.fir_number FROM CourtProceeding p JOIN Court c ON c.court_id=p.court_id JOIN Cases cs ON cs.case_id=p.case_id' },
};
